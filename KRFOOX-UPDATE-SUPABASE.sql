-- KRFOOX: additions for configurable booking interval, time blocks, and announcements
-- Run once in Supabase SQL Editor. Does not delete existing data.
ALTER TABLE public.salon_settings ADD COLUMN IF NOT EXISTS booking_interval integer NOT NULL DEFAULT 20;

CREATE TABLE IF NOT EXISTS public.salon_blocked_slots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  block_date date NOT NULL,
  start_time time NOT NULL,
  end_time time NOT NULL,
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT salon_blocked_slots_valid_range CHECK (start_time < end_time)
);

CREATE TABLE IF NOT EXISTS public.announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  body text NOT NULL,
  published boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.salon_blocked_slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.announcements ENABLE ROW LEVEL SECURITY;

-- Public clients can read published announcements and blocked time ranges.
DROP POLICY IF EXISTS "Public can read published announcements" ON public.announcements;
CREATE POLICY "Public can read published announcements" ON public.announcements FOR SELECT TO anon, authenticated USING (published = true);
DROP POLICY IF EXISTS "Authenticated can manage announcements" ON public.announcements;
CREATE POLICY "Authenticated can manage announcements" ON public.announcements FOR ALL TO authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Public can read blocked slots" ON public.salon_blocked_slots;
CREATE POLICY "Public can read blocked slots" ON public.salon_blocked_slots FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated can manage blocked slots" ON public.salon_blocked_slots;
CREATE POLICY "Authenticated can manage blocked slots" ON public.salon_blocked_slots FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- Ensure public client can read the schedule settings row. If equivalent policies already exist, these named policies are harmless.
ALTER TABLE public.salon_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public can read salon settings" ON public.salon_settings;
CREATE POLICY "Public can read salon settings" ON public.salon_settings FOR SELECT TO anon, authenticated USING (true);
