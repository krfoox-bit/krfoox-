-- Удаляем политики на этих таблицах, чтобы старые правила не расширяли доступ.
do $$
declare p record;
begin
 for p in select schemaname,tablename,policyname from pg_policies
  where schemaname='public' and tablename in ('bookings','salon_settings','sites','reviews','site_photos','announcements')
 loop execute format('drop policy if exists %I on %I.%I',p.policyname,p.schemaname,p.tablename); end loop;
end $$;

