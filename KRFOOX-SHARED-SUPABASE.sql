-- KRFOOX: общая база для клиентского сайта и панели владельца.
-- Выполните один раз в Supabase -> SQL Editor -> New query -> Run.
-- Используется текущий проект с уже существующей таблицей bookings:
-- https://wjvuffwegkyrongdxyni.supabase.co
-- Скрипт не удаляет существующие записи.

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  client_name text not null,
  phone text not null,
  booking_date date not null,
  booking_time time not null,
  service text,
  status text not null default 'confirmed',
  created_at timestamptz not null default now()
);
alter table public.bookings add column if not exists client_name text;
alter table public.bookings add column if not exists phone text;
alter table public.bookings add column if not exists booking_date date;
alter table public.bookings add column if not exists booking_time time;
alter table public.bookings add column if not exists service text;
alter table public.bookings add column if not exists status text default 'confirmed';
alter table public.bookings add column if not exists created_at timestamptz default now();
alter table public.bookings enable row level security;

-- Settings field names match both the client page and admin.html.
create table if not exists public.salon_settings (
  id integer primary key default 1 check (id = 1),
  "open" boolean not null default true,
  open_at time not null default '08:00',
  close_at time not null default '00:00',
  close_datetime timestamptz,
  reopen_datetime timestamptz,
  updated_at timestamptz not null default now()
);
alter table public.salon_settings add column if not exists "open" boolean not null default true;
alter table public.salon_settings add column if not exists open_at time not null default '08:00';
alter table public.salon_settings add column if not exists close_at time not null default '00:00';
alter table public.salon_settings add column if not exists close_datetime timestamptz;
alter table public.salon_settings add column if not exists reopen_datetime timestamptz;
alter table public.salon_settings add column if not exists is_open boolean;
insert into public.salon_settings(id,"open",open_at,close_at) values(1,true,'08:00','00:00') on conflict(id) do nothing;
update public.salon_settings set "open"=coalesce(is_open,"open") where is_open is not null;

create table if not exists public.sites (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  client_name text not null,
  comment text not null,
  rating integer not null default 5 check(rating between 1 and 5),
  published boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.site_photos (
  id bigint generated by default as identity primary key,
  url text not null,
  storage_path text,
  caption text default '',
  published boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.sites enable row level security;
alter table public.reviews enable row level security;
alter table public.site_photos enable row level security;
alter table public.announcements enable row level security;

-- Drop named policies first so this setup can be rerun.
drop policy if exists "KRFOOX public booking insert" on public.bookings;
drop policy if exists "KRFOOX admin booking read" on public.bookings;
drop policy if exists "KRFOOX admin booking update" on public.bookings;
drop policy if exists "KRFOOX public settings read" on public.salon_settings;
drop policy if exists "KRFOOX admin settings manage" on public.salon_settings;
drop policy if exists "KRFOOX admin sites manage" on public.sites;
drop policy if exists "KRFOOX public published reviews read" on public.reviews;
drop policy if exists "KRFOOX public review submit" on public.reviews;
drop policy if exists "KRFOOX admin reviews manage" on public.reviews;
drop policy if exists "KRFOOX public published photos read" on public.site_photos;
drop policy if exists "KRFOOX admin photos manage" on public.site_photos;
drop policy if exists "KRFOOX public published announcements read" on public.announcements;
drop policy if exists "KRFOOX admin announcements manage" on public.announcements;

create policy "KRFOOX public booking insert" on public.bookings for insert to anon,authenticated
with check(client_name is not null and length(trim(client_name))>0 and phone is not null and length(trim(phone))>0 and booking_date is not null and booking_time is not null);
create policy "KRFOOX admin booking read" on public.bookings for select to authenticated using(true);
create policy "KRFOOX admin booking update" on public.bookings for update to authenticated using(true) with check(true);

create policy "KRFOOX public settings read" on public.salon_settings for select to anon,authenticated using(true);
create policy "KRFOOX admin settings manage" on public.salon_settings for all to authenticated using(true) with check(true);
create policy "KRFOOX admin sites manage" on public.sites for all to authenticated using(true) with check(true);

create policy "KRFOOX public published reviews read" on public.reviews for select to anon,authenticated using(published=true);
create policy "KRFOOX public review submit" on public.reviews for insert to anon,authenticated with check(published=false and length(trim(client_name))>0 and length(trim(comment))>0 and rating between 1 and 5);
create policy "KRFOOX admin reviews manage" on public.reviews for all to authenticated using(true) with check(true);

create policy "KRFOOX public published photos read" on public.site_photos for select to anon,authenticated using(published=true);
create policy "KRFOOX admin photos manage" on public.site_photos for all to authenticated using(true) with check(true);
create policy "KRFOOX public published announcements read" on public.announcements for select to anon,authenticated using(published=true);
create policy "KRFOOX admin announcements manage" on public.announcements for all to authenticated using(true) with check(true);

grant usage on schema public to anon,authenticated;
grant select,insert on public.bookings to anon,authenticated;
grant select,update on public.bookings to authenticated;
grant select on public.salon_settings to anon,authenticated;
grant insert,update,delete on public.salon_settings to authenticated;
grant select,insert,update,delete on public.sites to authenticated;
grant select,insert on public.reviews to anon,authenticated;
grant update,delete,select on public.reviews to authenticated;
grant select on public.site_photos to anon,authenticated;
grant insert,update,delete on public.site_photos to authenticated;
grant select on public.announcements to anon,authenticated;
grant insert,update,delete on public.announcements to authenticated;

