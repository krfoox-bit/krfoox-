drop policy if exists "KRFOOX public view photos" on storage.objects;
drop policy if exists "KRFOOX authenticated upload photos" on storage.objects;
drop policy if exists "KRFOOX authenticated delete photos" on storage.objects;
create policy "KRFOOX public view photos" on storage.objects for select to anon,authenticated using(bucket_id='krfoox-photos');
create policy "KRFOOX authenticated upload photos" on storage.objects for insert to authenticated with check(bucket_id='krfoox-photos');
create policy "KRFOOX authenticated delete photos" on storage.objects for delete to authenticated using(bucket_id='krfoox-photos');

