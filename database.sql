alter table public.bookings add column if not exists booking_date date;
alter table public.bookings add column if not exists booking_time time;
alter table public.bookings add column if not exists service text;
alter table public.bookings add column if not exists status text default 'confirmed';
alter table public.bookings add column if not exists created_at timestamptz default now();

-- Безопасно отдаём клиентской странице только занятые временные интервалы,
-- не раскрывая имена и телефоны клиентов.
create or replace function public.krfoox_booked_times(p_date_from date)
returns table(booking_date date, booking_time time)
language sql
stable
security definer
set search_path = public
as $function$
  select b.booking_date, b.booking_time
  from public.bookings b
  where b.booking_date >= p_date_from
    and coalesce(lower(b.status), 'confirmed') not in ('cancelled','canceled');
$function$;
revoke all on function public.krfoox_booked_times(date) from public;
grant execute on function public.krfoox_booked_times(date) to anon, authenticated;

