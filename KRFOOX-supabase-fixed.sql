-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'krfoox-photos',
  'krfoox-photos',
  true,
  8388608,
  array['image/jpeg','image/png','image/webp','image/gif']
)
on conflict (id) do update
set public = true,
    file_size_limit = 8388608,
    allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "KRFOOX public view photos" on storage.objects;
drop policy if exists "KRFOOX authenticated upload photos" on storage.objects;
drop policy if exists "KRFOOX authenticated delete photos" on storage.objects;
drop policy if exists "KRFOOX owner upload photos" on storage.objects;
drop policy if exists "KRFOOX owner update photos" on storage.objects;
drop policy if exists "KRFOOX owner delete photos" on storage.objects;

-- Публичный бакет сам позволяет читать объекты по URL.
-- Эта политика также позволяет просматривать/листать объекты этого бакета.
create policy "KRFOOX public view photos"
on storage.objects for select to anon, authenticated
using (bucket_id = 'krfoox-photos');

create policy "KRFOOX owner upload photos"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'krfoox-photos'
  and (select auth.jwt() ->> 'email') = 'krfoox@gmail.com'
);

create policy "KRFOOX owner update photos"
on storage.objects for update to authenticated
using (
  bucket_id = 'krfoox-photos'
  and (select auth.jwt() ->> 'email') = 'krfoox@gmail.com'
)
with check (
  bucket_id = 'krfoox-photos'
  and (select auth.jwt() ->> 'email') = 'krfoox@gmail.com'
);

create policy "KRFOOX owner delete photos"
on storage.objects for delete to authenticated
using (
  bucket_id = 'krfoox-photos'
  and (select auth.jwt() ->> 'email') = 'krfoox@gmail.com'
);

