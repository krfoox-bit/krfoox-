-- =========================================================
-- KRFOOX BARBERSHOP — SUPABASE DATABASE SETUP
-- For client HTML calling:
--   krfoox_booked_times(p_date_from)
--   krfoox_create_booking(p_client_name, p_phone,
--                        p_booking_date, p_booking_time, p_service)
--
-- IMPORTANT:
-- If public.bookings already exists, review its columns and data
-- before running this script. Do not run unchanged against an
-- existing production table without a backup.
-- =========================================================

CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    booking_date DATE NOT NULL,
    booking_time TIME NOT NULL,
    service TEXT NOT NULL DEFAULT 'Запись',
    status TEXT NOT NULL DEFAULT 'confirmed'
        CHECK (status IN ('pending', 'confirmed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT bookings_valid_time
        CHECK (booking_time >= TIME '08:00' AND booking_time < TIME '24:00')
);

ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

-- Prevent two active bookings for the same date/time.
-- If existing active duplicates exist, resolve them before creating this index.
CREATE UNIQUE INDEX IF NOT EXISTS bookings_unique_active_slot
ON public.bookings (booking_date, booking_time)
WHERE status <> 'cancelled';

CREATE INDEX IF NOT EXISTS idx_bookings_date
ON public.bookings (booking_date);

-- Return occupied slots from a date onwards.
CREATE OR REPLACE FUNCTION public.krfoox_booked_times(p_date_from DATE DEFAULT CURRENT_DATE)
RETURNS TABLE (booking_date DATE, booking_time TIME, status TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT b.booking_date, b.booking_time, b.status
    FROM public.bookings AS b
    WHERE b.booking_date >= p_date_from
      AND b.status <> 'cancelled'
    ORDER BY b.booking_date, b.booking_time;
$$;

-- Create a booking atomically. The unique index prevents double booking.
CREATE OR REPLACE FUNCTION public.krfoox_create_booking(
    p_client_name TEXT,
    p_phone TEXT,
    p_booking_date DATE,
    p_booking_time TIME,
    p_service TEXT DEFAULT 'Запись'
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    new_id BIGINT;
BEGIN
    IF NULLIF(BTRIM(p_client_name), '') IS NULL THEN
        RETURN json_build_object('ok', false, 'message', 'Укажите имя клиента.');
    END IF;

    IF NULLIF(BTRIM(p_phone), '') IS NULL THEN
        RETURN json_build_object('ok', false, 'message', 'Укажите номер телефона.');
    END IF;

    IF p_booking_date IS NULL OR p_booking_date < CURRENT_DATE THEN
        RETURN json_build_object('ok', false, 'message', 'Выберите сегодняшнюю или будущую дату.');
    END IF;

    IF p_booking_time IS NULL
       OR p_booking_time < TIME '08:00'
       OR p_booking_time >= TIME '24:00'
       OR MOD(EXTRACT(HOUR FROM p_booking_time)::INTEGER * 60
              + EXTRACT(MINUTE FROM p_booking_time)::INTEGER - 480, 20) <> 0 THEN
        RETURN json_build_object('ok', false, 'message', 'Выберите время из доступных интервалов.');
    END IF;

    INSERT INTO public.bookings (
        client_name, phone, booking_date, booking_time, service, status
    )
    VALUES (
        BTRIM(p_client_name), BTRIM(p_phone), p_booking_date,
        p_booking_time, COALESCE(NULLIF(BTRIM(p_service), ''), 'Запись'), 'confirmed'
    )
    RETURNING id INTO new_id;

    RETURN json_build_object('ok', true, 'id', new_id);
EXCEPTION
    WHEN unique_violation THEN
        RETURN json_build_object(
            'ok', false,
            'message', 'Это время уже занято. Пожалуйста, выберите другое время.'
        );
END;
$$;

REVOKE ALL ON FUNCTION public.krfoox_booked_times(DATE) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.krfoox_create_booking(TEXT, TEXT, DATE, TIME, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.krfoox_booked_times(DATE) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.krfoox_create_booking(TEXT, TEXT, DATE, TIME, TEXT) TO anon, authenticated;
GRANT USAGE ON SCHEMA public TO anon, authenticated;

