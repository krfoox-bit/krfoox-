-- Return only booked date/time/status values needed by the public booking calendar.
create or replace function public.krfoox_booked_times(p_date_from date default current_date)
returns table (booking_date date, booking_time time, status text)
language sql stable security definer set search_path = public
as $$
  select b.booking_date, b.booking_time, b.status
  from public.bookings b
  where b.booking_date >= coalesce(p_date_from, current_date)
    and lower(coalesce(b.status, 'confirmed')) not in ('cancelled', 'canceled')
  order by b.booking_date, b.booking_time;
$$;
revoke all on function public.krfoox_booked_times(date) from public;
grant execute on function public.krfoox_booked_times(date) to anon, authenticated;

-- Atomically check availability and create a booking. The client never needs direct public SELECT on bookings.
create or replace function public.krfoox_create_booking(
  p_client_name text,
  p_phone text,
  p_booking_date date,
  p_booking_time time,
  p_service text default 'Запись'
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_settings public.salon_settings%rowtype;
  v_id text;
  v_end integer;
  v_start integer;
  v_requested integer;
begin
  if coalesce(length(trim(p_client_name)), 0) not between 1 and 80 then
    return jsonb_build_object('ok', false, 'message', 'Укажите имя длиной до 80 символов.');
  end if;
  if coalesce(length(trim(p_phone)), 0) not between 5 and 30 then
    return jsonb_build_object('ok', false, 'message', 'Проверьте номер телефона.');
  end if;
  if p_booking_date < current_date then
    return jsonb_build_object('ok', false, 'message', 'Нельзя записаться на прошедшую дату.');
  end if;

  select * into v_settings from public.salon_settings where id = 1;
  if not found then
    v_settings.open := true; v_settings.open_at := '08:00'; v_settings.close_at := '00:00';
  end if;
  if not coalesce(v_settings.open, true) then
    return jsonb_build_object('ok', false, 'message', 'Онлайн-запись временно закрыта.');
  end if;

  v_start := extract(hour from coalesce(v_settings.open_at, time '08:00'))::integer * 60
             + extract(minute from coalesce(v_settings.open_at, time '08:00'))::integer;
  v_end := extract(hour from coalesce(v_settings.close_at, time '00:00'))::integer * 60
           + extract(minute from coalesce(v_settings.close_at, time '00:00'))::integer;
  if v_end = 0 then v_end := 1440; end if;
  v_requested := extract(hour from p_booking_time)::integer * 60 + extract(minute from p_booking_time)::integer;
  if v_requested < v_start or v_requested >= v_end or mod(v_requested - v_start, 20) <> 0 then
    return jsonb_build_object('ok', false, 'message', 'Это время не входит в расписание салона.');
  end if;

  -- Serialize competing requests for the same date/time to prevent double bookings.
  perform pg_advisory_xact_lock(hashtext(p_booking_date::text), hashtext(p_booking_time::text));
  if exists (
    select 1 from public.bookings b
    where b.booking_date = p_booking_date and b.booking_time = p_booking_time
      and lower(coalesce(b.status, 'confirmed')) not in ('cancelled', 'canceled')
  ) then
    return jsonb_build_object('ok', false, 'message', 'Это время уже занято. Выбери другое.');
  end if;

  insert into public.bookings (client_name, phone, booking_date, booking_time, service, status)
  values (trim(p_client_name), trim(p_phone), p_booking_date, p_booking_time, coalesce(nullif(trim(p_service), ''), 'Запись'), 'confirmed')
  returning id::text into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end;
$$;
revoke all on function public.krfoox_create_booking(text, text, date, time, text) from public;
grant execute on function public.krfoox_create_booking(text, text, date, time, text) to anon, authenticated;

