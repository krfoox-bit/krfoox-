on public.bookings for insert to anon, authenticated
with check (
  client_name is not null and length(trim(client_name)) > 0
  and phone is not null and length(trim(phone)) > 0
  and booking_date is not null and booking_time is not null
);

-- Владелец: чтение и управление всеми бронированиями.
create policy "KRFOOX owner booking select"
on public.bookings for select to authenticated
using ((select auth.jwt() ->> 'email') = 'krfoox@gmail.com');

