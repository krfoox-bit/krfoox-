-- KRFOOX Barbershop: shared Supabase schema for client website + admin panel
-- Run once in Supabase -> SQL Editor. Uses the existing Supabase project.
-- This script uses CREATE TABLE IF NOT EXISTS and does not delete existing data.

create extension if not exists pgcrypto;

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  client_name text not null,
  phone text not null,
  booking_date date not null,
  booking_time time not null,
  service text not null default 'Запись',
  status text not null default 'confirmed',
  created_at timestamptz not null default now()
);
create index if not exists bookings_date_time_idx on public.bookings (booking_date, booking_time);

create table if not exists public.salon_settings (
  id integer primary key default 1 check (id = 1),
  open boolean not null default true,
  open_at time not null default '08:00',
  close_at time not null default '00:00',
  close_datetime timestamptz,
  reopen_datetime timestamptz,
  updated_at timestamptz not null default now()
);
insert into public.salon_settings (id, open, open_at, close_at)
values (1, true, '08:00', '00:00') on conflict (id) do nothing;

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  client_name text not null,
  comment text not null,
  rating integer not null default 5 check (rating between 1 and 5),
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.site_photos (
  id bigint generated by default as identity primary key,
  url text not null,
  caption text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.sites (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  created_at timestamptz not null default now()
);
