 reopen_datetime timestamptz,
 updated_at timestamptz not null default now()
);
alter table public.salon_settings add column if not exists "open" boolean not null default true;
alter table public.salon_settings add column if not exists open_at time not null default '08:00';
alter table public.salon_settings add column if not exists close_at time not null default '00:00';
alter table public.salon_settings add column if not exists close_datetime timestamptz;
alter table public.salon_settings add column if not exists reopen_datetime timestamptz;
alter table public.salon_settings add column if not exists is_open boolean;
insert into public.salon_settings(id,"open",open_at,close_at)
values(1,true,'08:00','00:00') on conflict(id) do nothing;
update public.salon_settings set "open"=is_open where is_open is not null;

create table if not exists public.sites (
